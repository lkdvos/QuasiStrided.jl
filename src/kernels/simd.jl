# Output update: scale_tile! is reused as-is from src/kernel.jl (it dispatches
# on `destination::QSTile` alone, with no kernel argument, so it is already
# shared — see that file's definition).
# ----------------------------------------------------------------------------

_unit_stride_rows(ax::AffineAxis) = ax.stride == 1
_unit_stride_rows(::ScatterAxis) = false

@inline function _acc_lane(acc::NTuple{NV,Vec{W,T}}, v::Int, j::Int, lane1::Int,
                            ::Val{NVECA}) where {NV,W,T,NVECA}
    return acc[v + NVECA * j + 1][lane1]
end

"""
    store_tile!(destination::QSTile, acc::NTuple{NV,SIMD.Vec{W,T}}, alpha::T, beta::T, kernel::SIMDKernel) -> destination

SIMD counterpart of `ScalarKernel`'s `store_tile!` (`src/kernel.jl`). Same
logical contract (design doc section 9): for every valid destination
coordinate `(i,j)` in `0:m-1 x 0:n-1`,

    C[i,j] = alpha * R[i,j] + beta * C[i,j]

with the identical alpha/beta shortcuts (`alpha==0` never reads the
accumulator; `beta==0` never reads old `C`; `beta==1` skips the
multiplication). Only the valid `m`-by-`n` rectangle is touched, so
accumulator lanes at `i>=m`/`j>=n` (kernel padding lanes, possibly nonfinite —
design doc section 8) are never read here and cannot propagate into the
stored output.

Two code paths, matching design doc section 9's "Unit row stride: use vector
loads/stores where valid... Other affine addressing: scalar strided handling
is sufficient initially... Column addressing is independent of row
addressing":

  * When `destination.rows` is an `AffineAxis` with `stride == 1` *and*
    `destination.storage` is a plain `Vector{T}`: for each valid column `j`
    (`destination.cols` may be affine or scattered — column addressing does
    not affect this choice), the full `m ÷ W` whole-width row blocks are
    updated with a genuine `SIMD.Vec{W,T}` load/store each; the remaining
    `m % W` rows (the tail) are updated one at a time via ordinary scalar
    loads/stores, extracting the corresponding lane of the same accumulator
    vector via `SIMD.Vec` indexing. The tail is deliberately scalar rather
    than a hardware-masked vector op: a masked `vload`/`vstore` still bounds-
    checks (and, at the LLVM level, still requires addressability of) the
    *entire* `W`-wide window even though only some lanes are read/written,
    and nothing in this package's contract guarantees a destination buffer
    has that much room past its last valid row (`checked_tile_storage_bounds`
    only validates the individual valid `(i,j)` addresses actually used, not
    every address in a partial vector's footprint). The scalar tail is
    exactly as safe as `ScalarKernel`'s store and never over-reads.
  * Otherwise (scattered rows, non-unit affine row stride, or non-`Vector`
    storage): every coordinate uses the scalar path, exactly as above without
    a vectorized fast branch — logically identical to `ScalarKernel`'s
    `store_tile!` on a `QSTile`, just extracting each accumulator scalar from
    its `SIMD.Vec` lane instead of a `Matrix`.

An empty destination (`m == 0` or `n == 0`) is a no-op.
"""
function store_tile!(destination::QSTile, acc::NTuple{NV,Vec{W,T}},
                      alpha::T, beta::T, kernel::SIMDKernel{MR,NR,T,W}) where {MR,NR,T,W,NV}
    m = nrows(destination)
    n = ncols(destination)
    (m == 0 || n == 0) && return destination

    if iszero(alpha)
        scale_tile!(destination, beta)
        return destination
    end

    NVECA = MR ÷ W
    nfull = m ÷ W  # whole W-row blocks entirely inside [0, m)

    if _unit_stride_rows(destination.rows) && destination.storage isa Vector{T}
        storage = destination.storage
        rows = destination.rows
        cols = destination.cols
        rowbase0 = destination.base + rows.base  # zero-based address at (i=0, j=0)'s row contribution
        @inbounds for j in 0:(n - 1)
            colbase = rowbase0 + axis_offset(cols, j)  # zero-based address of (i=0, j)
            for v in 0:(nfull - 1)
                idx = colbase + v * W + 1  # one-based storage index of row v*W
                rvec = acc[v + NVECA * j + 1]
                if iszero(beta)
                    outvec = alpha * rvec
                elseif isone(beta)
                    outvec = muladd(alpha, rvec, vload(Vec{W,T}, storage, idx))
                else
                    outvec = muladd(alpha, rvec, beta * vload(Vec{W,T}, storage, idx))
                end
                vstore(outvec, storage, idx)
            end
            for i in (nfull * W):(m - 1)
                idx = colbase + i + 1
                r = _acc_lane(acc, i ÷ W, j, (i % W) + 1, Val(NVECA))
                if iszero(beta)
                    storage[idx] = alpha * r
                elseif isone(beta)
                    storage[idx] = muladd(alpha, r, storage[idx])
                else
                    storage[idx] = muladd(alpha, r, beta * storage[idx])
                end
            end
        end
        return destination
    end

    @inbounds for j in 0:(n - 1), i in 0:(m - 1)
        r = _acc_lane(acc, i ÷ W, j, (i % W) + 1, Val(NVECA))
        if iszero(beta)
            tile_store!(destination, i, j, alpha * r)
        elseif isone(beta)
            tile_store!(destination, i, j, muladd(alpha, r, tile_load(destination, i, j)))
        else
            tile_store!(destination, i, j, muladd(alpha, r, beta * tile_load(destination, i, j)))
        end
    end
    return destination
end

"""
    execute_tile!(kernel::SIMDKernel, destination::QSTile, packed_a, packed_b, kc::Int, alpha, beta) -> destination

SIMD counterpart of `ScalarKernel`'s `execute_tile!` on a `QSTile`
(`src/kernel.jl`); same checked composition of `zero_accumulator`,
`accumulate` and `store_tile!`, the same validation order (destination
extent vs. kernel shape, `kc >= 0`, `checked_tile_storage_bounds` before any
unchecked path — including before the `kc==0`/`alpha==0` short-circuit, per
the Phase 2b Fable review fix this mirrors — then packed-buffer length
against `packed_a_length`/`packed_b_length`), and the same short-circuit
(`kc==0` or `alpha==0`: apply only beta scaling, never read `packed_a`/
`packed_b`).

Numerically matches `ScalarKernel`'s `execute_tile!` on the same inputs only
to within a tolerance (never bitwise): the accumulation order and FMA
grouping differ (design doc section 8: "FMA behavior and panel grouping can
change rounding").
"""
function execute_tile!(kernel::SIMDKernel{MR,NR,T,W}, destination::QSTile,
                        packed_a::AbstractVector{T}, packed_b::AbstractVector{T},
                        kc::Int, alpha, beta) where {MR,NR,T,W}
    m = nrows(destination)
    n = ncols(destination)
    m <= MR || throw(ArgumentError("destination valid row extent $m exceeds mr(kernel) = $MR"))
    n <= NR || throw(ArgumentError("destination valid column extent $n exceeds nr(kernel) = $NR"))
    kc >= 0 || throw(ArgumentError("execute_tile! requires kc >= 0, got kc = $kc"))

    alphaT = convert(T, alpha)
    betaT = convert(T, beta)

    (m == 0 || n == 0) && return destination

    # Fable review (Phase 2b) fix, preserved here: validate reachable
    # destination storage bounds before any unchecked path, including the
    # short-circuit below.
    checked_tile_storage_bounds(destination)

    if kc == 0 || iszero(alphaT)
        scale_tile!(destination, betaT)
        return destination
    end

    length(packed_a) >= packed_a_length(kernel, kc) ||
        throw(DimensionMismatch("execute_tile!: packed_a has length $(length(packed_a)), " *
                                 "need at least packed_a_length(kernel, kc=$kc) = $(packed_a_length(kernel, kc))"))
    length(packed_b) >= packed_b_length(kernel, kc) ||
        throw(DimensionMismatch("execute_tile!: packed_b has length $(length(packed_b)), " *
                                 "need at least packed_b_length(kernel, kc=$kc) = $(packed_b_length(kernel, kc))"))

    acc = zero_accumulator(kernel)
    acc = accumulate(kernel, acc, packed_a, packed_b, kc)
    store_tile!(destination, acc, alphaT, betaT, kernel)
    return destination
end
